"""Generate a shared Qt 6 palette without requiring Qt Python bindings."""

import configparser
import hashlib
from pathlib import Path
import re

from .integrations import ini_section_text, read_text


def blend(first, second, amount):
    channels = [round(int(first[i:i + 2], 16) * (1 - amount) + int(second[i:i + 2], 16) * amount)
                for i in (1, 3, 5)]
    return '#' + ''.join(f'{value:02x}' for value in channels)


def scheme_text(theme):
    bg, fg = theme.colors['primary']['background'], theme.colors['primary']['foreground']
    accent = theme.roles['accent']
    # QPalette::ColorRole indices, including NoRole (17) and Qt 6.6 Accent (21).
    active = [fg, bg, blend(bg, fg, .3), blend(bg, fg, .15), blend(bg, '#000000', .25),
              blend(bg, fg, .4), fg, fg, fg, bg, bg, blend(bg, '#000000', .65),
              fg, bg, accent, theme.colors['normal']['magenta'], bg, bg, bg, fg,
              blend(bg, fg, .55), accent]
    disabled = active.copy()
    for index in (0, 6, 7, 8, 12, 14, 15, 19, 20, 21):
        disabled[index] = blend(bg, active[index], .5)
    def row(values):
        return ', '.join('#ff' + color[1:] for color in values)
    return ('[ColorScheme]\nactive_colors=' + row(active) + '\n'
            'inactive_colors=' + row(active) + '\ndisabled_colors=' + row(disabled) + '\n')


def settings_text(text, palette_path, scheme):
    parser = configparser.RawConfigParser(strict=False)
    parser.read_string(text)
    values = {'custom_palette': 'true', 'color_scheme_path': setting_string(str(palette_path))}
    if not parser.has_option('Appearance', 'style'):
        values['style'] = 'Fusion'
    text = re.sub(r'^# chthm palette-sha256=[0-9a-f]{64}\r?\n', '', text, flags=re.M)
    text = ini_section_text(text, 'Appearance', values)
    # The plugin watches the configuration directory, not the colors subdirectory.
    # Changing this signature makes the config replace trigger its reload watcher.
    return '# chthm palette-sha256=' + hashlib.sha256(scheme.encode()).hexdigest() + '\n' + text


def setting_string(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r') + '"'


def desktop_argument(value):
    escaped = re.sub(r'(["`$\\])', r'\\\1', value.replace('%', '%%'))
    return '"' + escaped.replace('\\', '\\\\') + '"'


def install_cleanup(config, data):
    """Remove the previous PCManFM-Qt stylesheet override during installation."""
    writes, removals = [], []
    stylesheet = config / 'chthm/pcmanfm-qt.qss'
    desktop = data / 'applications/pcmanfm-qt.desktop'
    text = read_text(desktop)
    if text:
        parser = configparser.RawConfigParser(strict=False)
        parser.read_string(text)
        command = parser.get('Desktop Entry', 'Exec', fallback='')
        pattern = (r'(?P<exe>"[^"]+"|\S+)\s+"?-stylesheet"?\s+'
                   + re.escape(desktop_argument(str(stylesheet))) + r'(?P<rest>\s+.*|$)')
        match = re.fullmatch(pattern, command)
        if match and Path(match['exe'].strip('"')).name == 'pcmanfm-qt':
            native = match['exe'] + match['rest']
            writes.append((desktop, ini_section_text(text, 'Desktop Entry', {'Exec': native})))
    if read_text(stylesheet).startswith('/* Generated by chthm: PCManFM-Qt only. */'):
        removals.append(stylesheet)
    return writes, removals
